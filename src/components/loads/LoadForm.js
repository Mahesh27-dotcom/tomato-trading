"use client";

import { useEffect, useState } from "react";
import { useRouter } from "next/navigation";
import { createClient } from "@/utils/supabase/client";
import { Field, PrimaryButton } from "@/components/ui/Shell";
import TextInput from "@/components/ui/TextInput";

function emptyRateLine() {
  return { key: crypto.randomUUID(), quantity: "", rate: "" };
}

export default function LoadForm() {
  const router = useRouter();
  const supabase = createClient();

  const [farmers, setFarmers] = useState([]);
  const [farmerId, setFarmerId] = useState("");
  const [loadDate, setLoadDate] = useState(() =>
    new Date().toISOString().slice(0, 10)
  );
  const [vehicleNumber, setVehicleNumber] = useState("");
  const [notes, setNotes] = useState("");
  const [rateLines, setRateLines] = useState([emptyRateLine()]);

  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");

  useEffect(() => {
    const loadFarmers = async () => {
      const { data } = await supabase
        .from("farmers")
        .select("id, name, village")
        .order("name");

      setFarmers(data || []);
    };

    loadFarmers();
  }, []);

  const updateLine = (key, field, value) => {
    setRateLines((lines) =>
      lines.map((l) => (l.key === key ? { ...l, [field]: value } : l))
    );
  };

  const addLine = () => setRateLines((lines) => [...lines, emptyRateLine()]);

  const removeLine = (key) => {
    setRateLines((lines) =>
      lines.length > 1 ? lines.filter((l) => l.key !== key) : lines
    );
  };

  const lineAmount = (line) => {
    const q = parseFloat(line.quantity) || 0;
    const r = parseFloat(line.rate) || 0;
    return q * r;
  };

  const totalQuantity = rateLines.reduce(
    (sum, l) => sum + (parseFloat(l.quantity) || 0),
    0
  );

  const totalAmount = rateLines.reduce(
    (sum, l) => sum + lineAmount(l),
    0
  );

  const handleSubmit = async (e) => {
    e.preventDefault();
    setError("");

    if (!farmerId) {
      setError("Please select a farmer.");
      return;
    }

    const validLines = rateLines.filter(
      (l) => parseFloat(l.quantity) > 0 && parseFloat(l.rate) > 0
    );

    if (validLines.length === 0) {
      setError("Add at least one valid quantity and rate.");
      return;
    }

    setLoading(true);

    const {
      data: { user },
    } = await supabase.auth.getUser();

    // Insert load (load_number generated by DB trigger)
    const { data: newLoad, error: loadError } = await supabase
      .from("loads")
      .insert({
        load_date: loadDate,
        farmer_id: farmerId,
        vehicle_number: vehicleNumber,
        total_quantity: totalQuantity,
        total_purchase_amount: totalAmount,
        notes,
        created_by: user.id,
      })
      .select()
      .single();

    if (loadError) {
      setError(loadError.message);
      setLoading(false);
      return;
    }

    // Insert purchase rate lines
    // IMPORTANT: Don't send "amount" because PostgreSQL generates it automatically.
    const rateRows = validLines.map((l) => ({
      load_id: newLoad.id,
      quantity: parseFloat(l.quantity),
      rate: parseFloat(l.rate),
    }));

    const { error: ratesError } = await supabase
      .from("purchase_rates")
      .insert(rateRows);

    if (ratesError) {
      setError(
        `Load was created (${newLoad.load_number}) but rate entries failed: ${ratesError.message}`
      );
      setLoading(false);
      return;
    }

    setLoading(false);
    router.push(`/dashboard/loads/${newLoad.id}`);
    router.refresh();
  };

  return (
    <form onSubmit={handleSubmit} className="space-y-5">
      <Field label="Farmer">
        <select
          required
          value={farmerId}
          onChange={(e) => setFarmerId(e.target.value)}
          className="input-base w-full rounded-2xl px-4 py-3.5 text-[15px] outline-none"
          style={{
            color: "var(--color-text)",
            backgroundColor: "var(--color-bg)",
            border: "1.5px solid var(--color-border)",
          }}
        >
          <option value="">Select farmer</option>
          {farmers.map((f) => (
            <option key={f.id} value={f.id}>
              {f.name} {f.village ? `(${f.village})` : ""}
            </option>
          ))}
        </select>
      </Field>

      <Field label="Load date">
        <input
          type="date"
          required
          value={loadDate}
          onChange={(e) => setLoadDate(e.target.value)}
          className="input-base w-full rounded-2xl px-4 py-3.5 text-[15px] outline-none"
          style={{
            color: "var(--color-text)",
            backgroundColor: "var(--color-bg)",
            border: "1.5px solid var(--color-border)",
          }}
        />
      </Field>

      <Field label="Vehicle number">
        <TextInput
          value={vehicleNumber}
          onChange={(e) => setVehicleNumber(e.target.value)}
          placeholder="e.g. KA01AB1234"
        />
      </Field>

      <div>
        <div className="flex items-center justify-between mb-2.5">
          <label
            className="text-[13px] font-medium"
            style={{ color: "var(--color-text)" }}
          >
            Purchase rates
          </label>

          <button
            type="button"
            onClick={addLine}
            className="text-[13px] font-medium"
            style={{ color: "var(--color-accent)" }}
          >
            + Add rate
          </button>
        </div>

        <div className="space-y-2.5">
          {rateLines.map((line, idx) => (
            <div
              key={line.key}
              className="rounded-2xl p-3.5"
              style={{
                backgroundColor: "var(--color-surface)",
                border: "1px solid var(--color-border)",
              }}
            >
              <div className="flex items-center justify-between mb-2.5">
                <span
                  className="text-[12px] font-medium"
                  style={{ color: "var(--color-text-muted)" }}
                >
                  Rate {idx + 1}
                </span>

                {rateLines.length > 1 && (
                  <button
                    type="button"
                    onClick={() => removeLine(line.key)}
                    className="text-[12px] font-medium"
                    style={{ color: "var(--color-danger)" }}
                  >
                    Remove
                  </button>
                )}
              </div>

              <div className="grid grid-cols-2 gap-2.5">
                <TextInput
                  type="number"
                  inputMode="decimal"
                  value={line.quantity}
                  onChange={(e) =>
                    updateLine(line.key, "quantity", e.target.value)
                  }
                  placeholder="Quantity (kg)"
                />

                <TextInput
                  type="number"
                  inputMode="decimal"
                  value={line.rate}
                  onChange={(e) =>
                    updateLine(line.key, "rate", e.target.value)
                  }
                  placeholder="Rate (₹/kg)"
                />
              </div>

              <p
                className="text-[12px] mt-2"
                style={{ color: "var(--color-text-muted)" }}
              >
                Amount: ₹{lineAmount(line).toFixed(2)}
              </p>
            </div>
          ))}
        </div>
      </div>

      <div
        className="rounded-2xl p-4 flex items-center justify-between"
        style={{ backgroundColor: "var(--color-success-bg)" }}
      >
        <div>
          <p
            className="text-[12px]"
            style={{ color: "var(--color-text-muted)" }}
          >
            Total quantity
          </p>

          <p
            className="text-[16px] font-semibold"
            style={{ color: "var(--color-text)" }}
          >
            {totalQuantity.toFixed(1)} kg
          </p>
        </div>

        <div className="text-right">
          <p
            className="text-[12px]"
            style={{ color: "var(--color-text-muted)" }}
          >
            Total amount
          </p>

          <p
            className="text-[18px] font-semibold"
            style={{ color: "var(--color-success)" }}
          >
            ₹{totalAmount.toFixed(2)}
          </p>
        </div>
      </div>

      <Field label="Notes">
        <textarea
          value={notes}
          onChange={(e) => setNotes(e.target.value)}
          placeholder="Any additional notes"
          rows={3}
          className="input-base w-full rounded-2xl px-4 py-3.5 text-[15px] outline-none resize-none"
          style={{
            color: "var(--color-text)",
            backgroundColor: "var(--color-bg)",
            border: "1.5px solid var(--color-border)",
          }}
        />
      </Field>

      {error && (
        <p
          className="text-[13px] rounded-2xl px-4 py-3"
          style={{
            backgroundColor: "var(--color-danger-bg)",
            color: "var(--color-danger)",
          }}
        >
          {error}
        </p>
      )}

      <PrimaryButton type="submit" loading={loading}>
        Save Load
      </PrimaryButton>
    </form>
  );
}